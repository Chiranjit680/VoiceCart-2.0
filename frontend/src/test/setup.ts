import "@testing-library/jest-dom";
import { cleanup } from "@testing-library/react";

// Unmount whatever each test rendered, so tests cannot see each other's DOM.
afterEach(cleanup);

Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => {},
  }),
});
